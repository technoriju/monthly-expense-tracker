const ENTRIES = Object.entries(KEYWORDS).flatMap(([key, words]) =>
  (words ?? []).map((w) => ({ key: key as CategoryKey, phrase: normalizeText(w) })),
);

export interface CategoryResult {
  categoryKey: CategoryKey | null;
  /** True when keywords of two or more different categories were heard. */
  uncertain: boolean;
}

/**
 * Keyword match → category key. Multi-word phrases win over the single words inside them
 * ("বাড়ি ভাড়া" → rent). Different categories heard together → no category (the user picks),
 * so an expense is never silently filed under the wrong one.
 */
export function matchCategory(tokens: readonly string[]): CategoryResult {
  const hits: { key: CategoryKey; start: number; length: number }[] = [];
  for (const { key, phrase } of ENTRIES) {
    const start = findPhrase(tokens, phrase);
    if (start >= 0) hits.push({ key, start, length: phrase.split(' ').length });
  }
  // A word inside a longer matched phrase belongs to that phrase ("travel" in "travel fare").
  const kept = hits.filter(
    (h) =>
      !hits.some(
        (o) =>
          o.length > h.length && o.start <= h.start && o.start + o.length >= h.start + h.length,
      ),
  );
  const keys = new Set(kept.map((h) => h.key));
  if (keys.size === 1) return { categoryKey: [...keys][0] ?? null, uncertain: false };
  return { categoryKey: null, uncertain: keys.size > 1 };
}
